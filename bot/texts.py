def _legal_links(config) -> str:
    links = []
    if config.offer_url:
        links.append(f'<a href="{config.offer_url}">оферта</a>')
    if config.privacy_url:
        links.append(f'<a href="{config.privacy_url}">политика обработки данных</a>')
    return ", ".join(links)



CSS = (ROOT / "style.css").read_text(encoding="utf-8")


def e(s):
    return html.escape(s, quote=False)


def slide_cover(s, acc, idx, total):
    chips = "".join(
        f'<div class="chip" style="--c:{c or acc}"><span>{e(a)}</span><b>{e(b)}</b></div>'
        for a, b, c in s["chips"]
    )
    return f"""
<div class="slide cover" style="--a:{acc}">
  <div class="glow"></div><div class="grid-bg"></div>
  <div class="top"><span class="kicker"><i></i>{e(s['kicker'])}</span><span class="pg">{idx:02d} / {total:02d}</span></div>
  <h1>{s['title']}</h1>
  <p class="sub">{e(s['sub'])}</p>
  <div class="chips">{chips}</div>
  <div class="cta"><span class="arrow">→</span>{e(s['cta'])}</div>
</div>"""


def head(title, acc, idx, total, sub=None):
    sub_html = f'<p class="lead">{e(sub)}</p>' if sub else ""
    return f"""<div class="top"><span class="kicker"><i></i>{e(title)}</span><span class="pg">{idx:02d} / {total:02d}</span></div>
<h2>{e(title)}</h2>{sub_html}"""


def slide_grid(s, acc, idx, total):
    cards = "".join(
        f'<div class="card" style="--c:{c or acc}"><span class="n">{i:02d}</span><h3>{e(t)}</h3><p>{e(d)}</p></div>'
        for i, (t, d, c) in enumerate(s["cards"], 1)
    )
    return f"""
<div class="slide light" style="--a:{acc}">
  {head(s['title'], acc, idx, total)}
  <div class="cards cols{s['cols']}">{cards}</div>
</div>"""


def slide_packages(s, acc, idx, total):
    out = []
    for name, price, term, items, hl in s["packages"]:
        lis = "".join(f"<li>{e(x)}</li>" for x in items)
        badge = '<span class="badge">Чаще выбирают</span>' if hl else ""
        prefix = "" if price.startswith("от") else "от "
        out.append(
            f'<div class="pkg{" hl" if hl else ""}">{badge}<h3>{e(name)}</h3>'
            f'<div class="price">{e(prefix + price)}</div><div class="term">{e(term)}</div><ul>{lis}</ul></div>'
        )
    return f"""
<div class="slide light" style="--a:{acc}">
  {head(s['title'], acc, idx, total)}
  <div class="pkgs">{''.join(out)}</div>
  <p class="note">{e(s['note'])}</p>
</div>"""


def slide_steps(s, acc, idx, total):
    steps = "".join(
        f'<div class="step"><span class="dot">{i}</span><h3>{e(t)}</h3><p>{e(d)}</p></div>'
        for i, (t, d) in enumerate(s["steps"], 1)
    )
    trust = "".join(f'<span><i>✓</i>{e(t)}</span>' for t in s["trust"])
    return f"""
<div class="slide dark" style="--a:{acc}">
  <div class="glow small"></div>
  {head(s['title'], acc, idx, total)}
  <div class="steps">{steps}</div>
  <div class="trust">{trust}</div>
  <div class="cta inline"><span class="arrow">→</span>Напишите в сообщения - ответим в течение часа</div>
</div>"""


def slide_flow(s, acc, idx, total):
    nodes = []
    for i, (n, t, d, c) in enumerate(s["nodes"]):
        if i:
            nodes.append('<div class="link">→</div>')
        nodes.append(f'<div class="node" style="--c:{c}"><span class="n">{n}</span><h3>{e(t)}</h3><p>{e(d)}</p></div>')
    return f"""
<div class="slide light" style="--a:{acc}">
  {head(s['title'], acc, idx, total, s.get('sub'))}
  <div class="flow">{''.join(nodes)}</div>
  <div class="cta dark-cta"><span class="arrow">→</span>Можно заказать одну услугу или всю связку со скидкой</div>
</div>"""


def slide_portfolio(s, acc, idx, total):
    feats = "".join(f'<li>{e(x)}</li>' for x in s["features"])
    return f"""
<div class="slide light" style="--a:{acc}">
  {head(s['title'], acc, idx, total)}
  <div class="pf">
    <div class="browser"><div class="bar"><i></i><i></i><i></i></div><img src="../assets/{s['desk']}"></div>
    <div class="phone"><img src="../assets/{s['mob']}"></div>
  </div>
  <div class="pf-info">
    <div class="pf-name"><b>{e(s['project'])}</b><span>{e(s['place'])}</span></div>
    <ul>{feats}</ul>
  </div>
</div>"""


RENDER = {
    "portfolio": slide_portfolio,
    "cover": slide_cover,
    "grid": slide_grid,
    "packages": slide_packages,
    "steps": slide_steps,
    "flow": slide_flow,
}


def main():
    out_dir = ROOT / "html"
    out_dir.mkdir(exist_ok=True)
    manifest = []
    for ad, cfg in ADS.items():
        total = len(cfg["slides"])
        for i, s in enumerate(cfg["slides"], 1):
            body = RENDER[s["type"]](s, cfg["acc"], i, total)
            body = re.sub(r">([^<]+)<", lambda m: ">" + re.sub(r"(\w+(?:-\w+)+)", r'<span class="nw">\1</span>', m.group(1)) + "<", body)
            doc = f"""<!doctype html><html lang="ru"><head><meta charset="utf-8">
<style>{CSS}</style></head><body>{body}</body></html>"""
            p = out_dir / f"{ad}-{i:02d}.html"
            p.write_text(doc, encoding="utf-8")
            manifest.append({"html": str(p), "png": f"{ad}/{i:02d}.png"})
    (ROOT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(manifest)} slides")


